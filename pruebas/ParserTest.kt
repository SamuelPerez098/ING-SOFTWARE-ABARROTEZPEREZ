var bad = 0
fun ok(name: String, c: Boolean, d: String = "") { if (!c) { bad++; println("  FALLA $name  -> $d") } else println("  OK    $name") }

val hoy = LocalDate.of(2026, 11, 22)
fun suite(p: QueryParser, tag: String) {
    println("=== suite: $tag ===")
    fun q(s: String) = p.parse(s)

    var r = q("Muéstrame todos los productos que caducan en las próximas 3 semanas")
    ok("caducan 3 semanas", r.intent == AssistantIntent.EXPIRING_SOON && r.params.days == 21 && r.params.limit == 50, r.toString())
    r = q("¿Cuáles son mis 5 productos más vendidos?")
    ok("top 5", r.intent == AssistantIntent.TOP_SELLING && r.params.limit == 5 && r.params.period == null, r.toString())
    r = q("¿Qué productos tienen pocas existencias?")
    ok("pocas existencias", r.intent == AssistantIntent.LOW_STOCK, r.toString())
    r = q("¿Cuáles son los productos agotados?")
    ok("agotados", r.intent == AssistantIntent.OUT_OF_STOCK, r.toString())
    r = q("¿Cuánto vendí durante esta semana?")
    ok("ventas semana", r.intent == AssistantIntent.SALES_TOTAL && r.params.period == TimePeriod.thisWeek(hoy), r.toString())
    r = q("¿Cuáles son los productos que menos se venden?")
    ok("menos vendidos", r.intent == AssistantIntent.LEAST_SELLING, r.toString())
    r = q("¿Qué productos no han tenido ventas durante el último mes?")
    ok("sin movimiento último mes", r.intent == AssistantIntent.NO_MOVEMENT && r.params.days == 30, r.toString())
    r = q("¿Cuánto dinero tengo invertido en inventario?")
    ok("valor inventario", r.intent == AssistantIntent.INVENTORY_VALUE, r.toString())
    r = q("¿Qué productos necesito comprar?")
    ok("reabastecer", r.intent == AssistantIntent.RESTOCK_NEEDS, r.toString())
    r = q("Muéstrame las ventas del mes anterior")
    ok("ventas mes anterior", r.intent == AssistantIntent.SALES_TOTAL && r.params.period == TimePeriod.lastMonth(hoy), r.toString())

    println("-- variantes --")
    r = q("¿Y cuáles fueron los menos vendidos?"); ok("menos vendidos (seguimiento)", r.intent == AssistantIntent.LEAST_SELLING, r.toString())
    r = q("que caduca esta semana"); ok("caduca esta semana (hoy domingo) = 1", r.intent == AssistantIntent.EXPIRING_SOON && r.params.days == 1, r.toString())
    r = QueryParser(clock = { LocalDate.of(2026, 11, 18) }).parse("que caduca esta semana"); ok("miércoles 18 -> hasta domingo 22 = 4 días", r.params.days == 4, r.toString())
    r = QueryParser(clock = { LocalDate.of(2026, 11, 18) }).parse("que caduca este mes"); ok("18 nov -> hasta 30 nov = 12 días", r.params.days == 12, r.toString())
    r = q("que productos se estan acabando"); ok("se están acabando -> pocas existencias", r.intent == AssistantIntent.LOW_STOCK, r.toString())
    r = q("productos que vencen el proximo mes"); ok("vencen próximo mes = 30", r.intent == AssistantIntent.EXPIRING_SOON && r.params.days == 30, r.toString())
    r = q("¿Qué productos ya caducaron?"); ok("ya caducaron -> caducados", r.intent == AssistantIntent.EXPIRED, r.toString())
    r = q("productos caducados"); ok("caducados", r.intent == AssistantIntent.EXPIRED, r.toString())
    r = q("lo que caduca en 10 dias"); ok("10 días", r.params.days == 10, r.toString())
    r = q("ventas de hoy"); ok("hoy", r.params.period == TimePeriod.today(hoy), r.toString())
    r = q("cuanto vendi ayer"); ok("ayer", r.params.period == TimePeriod.yesterday(hoy), r.toString())
    r = q("ventas de la semana pasada"); ok("semana pasada", r.params.period == TimePeriod.lastWeek(hoy), r.toString())
    r = q("compara las ventas de este mes contra el mes anterior")
    ok("comparar mes vs mes anterior", r.intent == AssistantIntent.SALES_COMPARE && r.params.period == TimePeriod.thisMonth(hoy) && r.params.comparePeriod == TimePeriod.lastMonth(hoy), r.toString())
    r = q("compara esta semana con la semana pasada")
    ok("comparar semanas", r.intent == AssistantIntent.SALES_COMPARE && r.params.period == TimePeriod.thisWeek(hoy) && r.params.comparePeriod == TimePeriod.lastWeek(hoy), r.toString())
    r = q("productos con menos de 10 unidades"); ok("umbral 10", r.intent == AssistantIntent.LOW_STOCK && r.params.threshold == 10, r.toString())
    r = q("top 10 mas vendidos de los ultimos 15 dias")
    ok("top 10 últimos 15 días", r.intent == AssistantIntent.TOP_SELLING && r.params.limit == 10 && r.params.period == TimePeriod.lastDays(15, hoy), r.toString())
    r = q("los tres productos mas vendidos"); ok("tres", r.params.limit == 3, r.toString())
    r = q("mermas de este mes"); ok("mermas", r.intent == AssistantIntent.SHRINKAGE && r.params.period == TimePeriod.thisMonth(hoy), r.toString())
    r = q("cuanto he perdido por mermas"); ok("pérdidas merma", r.intent == AssistantIntent.SHRINKAGE, r.toString())
    r = q("baja rotacion"); ok("baja rotación", r.intent == AssistantIntent.LOW_ROTATION, r.toString())
    r = q("cuantas coca cola tengo"); ok("búsqueda coca cola", r.intent == AssistantIntent.SEARCH_PRODUCT && r.params.productQuery == "coca cola", r.toString())
    r = q("precio de las sabritas"); ok("búsqueda sabritas", r.intent == AssistantIntent.SEARCH_PRODUCT && r.params.productQuery == "sabritas", r.toString())
    r = q("busca"); ok("busca sin producto -> query null", r.intent == AssistantIntent.SEARCH_PRODUCT && r.params.productQuery == null, r.toString())
    r = q("hola"); ok("saludo -> ayuda", r.intent == AssistantIntent.HELP, r.toString())
    r = q("que puedes hacer"); ok("ayuda", r.intent == AssistantIntent.HELP, r.toString())
    r = q("blablabla"); ok("desconocido", r.intent == AssistantIntent.UNKNOWN, r.toString())
    r = q("   "); ok("vacío", r.intent == AssistantIntent.UNKNOWN)
    r = q("¿qué productos se están acabando?"); println("  (info) 'se están acabando' -> ${r.intent}")
    r = q("productos que no se han vendido en 15 dias"); ok("sin ventas 15 días", r.intent == AssistantIntent.NO_MOVEMENT && r.params.days == 15, r.toString())
    r = q("DROP TABLE producto; --"); ok("inyección -> desconocido/inofensivo", r.intent == AssistantIntent.UNKNOWN, r.toString())

}

fun nuevas(p: QueryParser) {
    println("=== Fase 4: ambigüedad, productos, coloquial ===")
    fun q(s: String) = p.parse(s)
    var r = q("ventas y caducidad")
    ok("ambiguo: ventas vs caducidad -> pregunta", r.clarification != null && r.clarification!!.contains("próximos a caducar") && r.clarification!!.contains("tus ventas"), r.toString())
    r = q("inventario")
    ok("débil: 'inventario' -> ofrece opciones", r.clarification != null && r.candidates.size == 3, r.toString())
    r = q("cuanto me deben"); ok("fiados -> remite a Clientes", r.clarification?.contains("Clientes") == true, r.toString())
    r = q("gracias"); ok("gracias -> respuesta directa", r.directReply != null && r.clarification == null, r.toString())
    r = q("cuantas cocas me quedan"); ok("producto plural -> SEARCH 'cocas'", r.intent == AssistantIntent.SEARCH_PRODUCT && r.params.productQuery == "cocas", r.toString())
    r = q("coca cola"); ok("solo el producto -> SEARCH", r.intent == AssistantIntent.SEARCH_PRODUCT && r.params.productQuery == "coca cola", r.toString())
    r = q("leche"); ok("'leche' -> SEARCH", r.intent == AssistantIntent.SEARCH_PRODUCT, r.toString())
    r = q("ventas de coca cola esta semana"); ok("ventas por producto -> aclara limitación", r.clarification?.contains("Coca-Cola") == true && r.intent == AssistantIntent.UNKNOWN, r.toString())
    r = q("cuando caduca la leche"); ok("caducidad por producto -> aclara", r.clarification?.contains("filtrar") == true, r.toString())
    r = q("productos caducados"); ok("sin falsos productos: caducados", r.intent == AssistantIntent.EXPIRED && r.clarification == null, r.toString())
    r = q("cuanta lana tengo en mercancia"); ok("coloquial: lana -> valor inventario", r.intent == AssistantIntent.INVENTORY_VALUE, r.toString())
    r = q("que me hace falta surtir"); ok("coloquial: hace falta surtir", r.intent == AssistantIntent.RESTOCK_NEEDS, r.toString())
    r = q("que se vende mas"); ok("coloquial: se vende más", r.intent == AssistantIntent.TOP_SELLING, r.toString())
    r = q("lo que se vende poco"); ok("coloquial: se vende poco", r.intent == AssistantIntent.LEAST_SELLING, r.toString())
    r = q("dame los mejores productos"); ok("coloquial: mejores productos", r.intent == AssistantIntent.TOP_SELLING, r.toString())
    r = q("productos danados"); ok("débil: dañados -> pregunta por mermas", r.clarification?.contains("mermas") == true, r.toString())
    r = q("cuantos productos agotados hay"); ok("cuántos agotados -> OUT (no búsqueda)", r.intent == AssistantIntent.OUT_OF_STOCK, r.toString())
    r = q("cuantas ventas hice hoy"); ok("cuántas ventas hoy -> ventas de hoy", r.intent == AssistantIntent.SALES_TOTAL && r.params.period == TimePeriod.today(hoy), r.toString())
    r = q("productos por acabarse"); ok("por acabarse -> pocas existencias", r.intent == AssistantIntent.LOW_STOCK, r.toString())
    r = q("QUE PRODUCTOS CADUCAN EN 2 SEMANAS??"); ok("mayúsculas y signos", r.intent == AssistantIntent.EXPIRING_SOON && r.params.days == 14, r.toString())
    r = q("¿Cuánto vendí más que ayer?"); println("  (info) 'vendí más que ayer' -> ${r.intent} ${r.clarification ?: ""}")
    r = q("asdf qwer"); ok("sin sentido -> UNKNOWN sin ejecutar", r.intent == AssistantIntent.UNKNOWN, r.toString())
}

fun main() {
    suite(QueryParser { hoy }, "sin catálogo")
    val cat = ProductCatalog({ listOf("Coca-Cola 600ml", "Leche Lala 1L", "Leche Alpura 1L", "Sabritas Original", "Jabón Zote", "Atún Dolores", "Galletas Marinela") })
    suite(QueryParser(cat) { hoy }, "con catálogo (sin regresiones)")
    nuevas(QueryParser(cat) { hoy })
    println("-- historial --")
    val f = File("/tmp/hist_test/h.jsonl"); f.parentFile.deleteRecursively()
    val s = ChatHistoryStore(f, maxMessages = 10)
    ok("vacío al inicio", s.load().isEmpty())
    s.append(ChatMessage(1, ChatRole.USER, "¿Cuánto vendí hoy? ñ \"comillas\" \n salto"))
    s.append(ChatMessage(2, ChatRole.ASSISTANT, "Vendiste \$54.00", ResultTable(listOf("A","B"), listOf(listOf("x","1"), listOf("y","2"))), listOf("nota"), 123L))
    s.append(ChatMessage(3, ChatRole.ASSISTANT, "bienvenida", persist = false))
    val l = ChatHistoryStore(f, 10).load()
    ok("2 mensajes persistidos (no la bienvenida)", l.size == 2, l.toString())
    ok("texto con comillas/saltos intacto", l[0].text == "¿Cuánto vendí hoy? ñ \"comillas\" \n salto")
    ok("tabla y notas intactas", l[1].table?.rows == listOf(listOf("x","1"), listOf("y","2")) && l[1].notes == listOf("nota") && l[1].timestamp == 123L)
    f.appendText("{línea dañada\n")
    ok("línea dañada ignorada", ChatHistoryStore(f, 10).load().size == 2)
    val c = ChatHistoryStore(File("/tmp/hist_test/c.jsonl"), maxMessages = 10)
    repeat(150) { c.append(ChatMessage(it.toLong(), ChatRole.USER, "m$it")) }
    val cl = ChatHistoryStore(File("/tmp/hist_test/c.jsonl"), 10).load()
    ok("recorte: conserva los últimos y no excede límite+100", cl.size <= 110 && cl.last().text == "m149", cl.size.toString())
    c.clear(); ok("clear", ChatHistoryStore(File("/tmp/hist_test/c.jsonl"), 10).load().isEmpty())
    println("Fallos: $bad"); if (bad > 0) System.exit(1)
}
